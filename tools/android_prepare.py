#!/usr/bin/env python3
"""Prepares Godot's Android Gradle build template (game/android/build, generated, not committed):
1. puts Google's Maven Central mirror first (Maven Central rate-limits proxied/CI traffic);
2. compileSdk / build tools 36 (Play's target API 36 requirement);
3. writes res/values/firebase.xml from the registered Firebase Android app, so FirebaseApp
   initialises at process start and FCM can show notifications while the game is closed.
The Firebase config is fetched by tools/build_clients.sh into build/firebase/google-services.json.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TPL = os.path.join(ROOT, "game", "android", "build")
MIRROR = 'maven { url "https://maven-central.storage-download.googleapis.com/maven2/" }'
PACKAGE = "my.otono.tinker"

# Google Play requires target API 36 (Android 16) for new apps and updates since 2026-08-31 (the preset
# sets target_sdk 36); the template compiles against 35, so raise compileSdk to match.
cfg = os.path.join(TPL, "config.gradle")
c = open(cfg).read()
c2 = re.sub(r"compileSdk(\s*):\s*\d+", r"compileSdk\1: 36", c)
c2 = re.sub(r"buildTools(\s*):\s*'[\d.]+'", r"buildTools\1: '36.0.0'", c2)
if c2 != c:
    open(cfg, "w").write(c2)

# R8 (Play Console: "DEX optimization Low", "obfuscation 1%"): TINKER_R8=1 shrinks + obfuscates the Java/
# Kotlin side of release builds. Godot's engine classes and our plugin are called from native code /
# by name, so they are kept whole; Firebase and Play Billing ship their own consumer rules. Off unless
# asked: a release with R8 goes to internal testing first (Play's pre-launch report runs it on devices).
bg = os.path.join(TPL, "build.gradle")
b = open(bg).read()
r8_on = os.environ.get("TINKER_R8", "0") == "1"
MARK = "// tinker-r8"
ANCHOR = "        release {\n            // Signing and zip-aligning are skipped for prebuilt builds, but"
if r8_on and MARK not in b and ANCHOR in b:
    b = b.replace(ANCHOR, "        release {\n"
                  "            minifyEnabled true  " + MARK + "\n"
                  "            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'tinker-proguard-rules.pro'  " + MARK + "\n"
                  "            // Signing and zip-aligning are skipped for prebuilt builds, but", 1)
    open(bg, "w").write(b)
elif not r8_on and MARK in b:
    open(bg, "w").write("\n".join(l for l in b.split("\n") if MARK not in l))
RULES = [
    "# Generated by tools/android_prepare.py (TINKER_R8=1). Do not edit.",
    "-keep class org.godotengine.** { *; }",
    "-keep class my.otono.** { *; }",
    "-keep class * extends org.godotengine.godot.plugin.GodotPlugin { *; }",
    "-keepattributes *Annotation*,Signature,InnerClasses,EnclosingMethod,SourceFile,LineNumberTable",
    "-dontwarn org.godotengine.**",
]
with open(os.path.join(TPL, "tinker-proguard-rules.pro"), "w") as f:
    f.write("\n".join(RULES) + "\n")

for name in ("build.gradle", "settings.gradle"):
    p = os.path.join(TPL, name)
    s = open(p).read()
    if MIRROR not in s:
        s = re.sub(r"(\n(\s*)google\(\)\n)", lambda m: m.group(1) + m.group(2) + MIRROR + "\n", s)
        open(p, "w").write(s)

gs_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "firebase", "google-services.json")
if not os.path.exists(gs_path):
    sys.exit("missing %s (run tools/build_clients.sh, which fetches it from Firebase)" % gs_path)
gs = json.load(open(gs_path))
client = next(c for c in gs["client"] if c["client_info"]["android_client_info"]["package_name"] == PACKAGE)
pi = gs["project_info"]
values = {
    "google_app_id": client["client_info"]["mobilesdk_app_id"],
    "google_api_key": client["api_key"][0]["current_key"],
    "gcm_defaultSenderId": pi["project_number"],
    "project_id": pi["project_id"],
    "google_storage_bucket": pi.get("storage_bucket", ""),
}
res = os.path.join(TPL, "res", "values")
os.makedirs(res, exist_ok=True)
with open(os.path.join(res, "firebase.xml"), "w") as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/android_prepare.py from Firebase. Do not edit or commit. -->\n<resources>\n')
    for k, v in values.items():
        f.write('    <string name="%s" translatable="false">%s</string>\n' % (k, v))
    f.write("</resources>\n")
print("android template prepared: mirror + firebase.xml (%s)" % values["google_app_id"])
